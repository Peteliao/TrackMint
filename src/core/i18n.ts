let ready = false;

function syncDocumentLanguage() {
  document.documentElement.lang = languageTag(currentLang());
  document.title = `${t('app.name')} · ${t('app.tagline')}`;
  const values = {
    description: t('app.slogan'),
    'application-name': t('app.name'),
    'apple-mobile-web-app-title': t('app.name')
  };
  for (const [name, content] of Object.entries(values)) {
    const meta = document.querySelector(`meta[name="${name}"]`);
    meta?.setAttribute('content', content);
  }
}

export async function initI18n() {
  await i18next.init({
    lng: resolvedLanguage(),
    fallbackLng: 'en',
    resources: {
      zh: { translation: zh },
      'zh-TW': { translation: zhTW },
      en: { translation: en },
      ja: { translation: ja },
      ko: { translation: ko },
      es: { translation: es }
    },
    interpolation: { escapeValue: false },
    returnNull: false
  });
  ready = true;
  syncDocumentLanguage();
}

export function t(key: string, opts: any = {}): string {
  if (!ready) return key;
  return i18next.t(key, opts) as string;
}

export function currentLang() { return i18next.language || resolvedLanguage(); }

export async function setLanguage(lang) {
  set('language', lang);
  await i18next.changeLanguage(lang === 'auto' ? resolvedLanguage() : lang);
  syncDocumentLanguage();
  emit('language:changed', currentLang());
}

